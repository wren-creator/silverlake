"""Turn the F11=Choices screens in `auth-f11-*` and `auth-prompt-keys` captures into `screens/promptchoices.py`.

    python -m silverlake.oracle.promptchoices captures/pub400/auth-prompt-keys.json captures/pub400/auth-f11-*.json > src/silverlake/screens/promptchoices.py

F11 on a prompt moves every field left by 13 columns and adds a hint column at column 50 that says what the field
takes ("Name, *CURLIB", "0-30", "*NO, *YES"). The labels stay, and the keyword that sat at column 34 goes. Only the
hints are kept, row by row, and each is matched to the page of the prompt it belongs to (a page of the plain prompt, or
a page of what F10 shows) by the rows and lengths of its input fields, so `screens/prompt.py` can draw the view from
what it already knows. A page that was never reached is simply not there."""

from __future__ import annotations

import json
import sys

from ..screens.promptspecs import SPECS
from .promptspec import _TITLE

HINT_COL, SHIFT = 50, 13


def _is_choices(snapshot: dict) -> bool:
    return any(r["col"] == HINT_COL and r["attr"] == "0x20" and 4 <= r["row"] <= 19 for r in snapshot["runs"])


def _page_key(rows: list) -> tuple:
    return tuple(sorted((row, length) for row, _, name, _, length, _ in rows if name))


def _page_keys(command: str) -> list[tuple[str, int, tuple]]:
    spec = SPECS[command]                       # the raw table: the first page is "rows", later ones are "pages"
    plain = [spec["rows"]] + [rows for rows, _ in spec.get("pages", [])]
    keys = [("pages", i, _page_key(rows)) for i, rows in enumerate(plain)]
    keys += [("more", i, _page_key(rows)) for i, (rows, _) in enumerate(spec.get("more", {}).get("pages", []))]
    return keys


def extract(captures: list[dict]) -> tuple[dict, list[str]]:
    """{command: {"pages": {page: {row: hint}}, "more": {...}}} and a list of anything that did not fit."""
    found: dict[str, dict] = {}
    problems: list[str] = []
    for cap in captures:
        for n, snap in enumerate(cap["snapshots"]):
            runs = snap["runs"]
            if not runs or runs[0]["row"] != 0 or not (m := _TITLE.search(runs[0]["text"])):
                continue
            command = m.group(1)
            if command not in SPECS or not _is_choices(snap):
                continue
            fields = sorted((f["row"], f["length"]) for f in snap["fields"])
            where = f"{command} in {cap.get('scenario', '?')} screen {n}"
            matches = [(kind, i) for kind, i, key in _page_keys(command) if list(key) == fields]
            if not matches:
                problems.append(f"{where}: no page has fields {fields}")
                continue
            hints: dict[int, str] = {}
            for r in runs:
                if r["col"] == HINT_COL and 4 <= r["row"] <= 19 and r["attr"] == "0x20":
                    if r["row"] in hints:
                        problems.append(f"{where}: two hints on row {r['row']}")
                    hints[r["row"]] = r["text"].rstrip()
            for kind, i in matches:                       # an ambiguous page is filled in for every page it could be
                slot = found.setdefault(command, {"pages": {}, "more": {}})[kind]
                if i in slot and slot[i] != hints:
                    problems.append(f"{where}: page {kind}[{i}] already has different hints")
                slot.setdefault(i, hints)
    return found, problems


def render(found: dict) -> str:
    out = ['"""Generated by `python -m silverlake.oracle.promptchoices`, from the F11=Choices screens of the PUB400 captures.',
           'Per command, per page of the plain prompt ("pages") or of what F10 shows ("more"): the hint beside each field,',
           'by row. Do not edit by hand."""', "", "from __future__ import annotations", "",
           "CHOICES: dict[str, dict] = {"]
    for command in sorted(found):
        out.append(f"    {command!r}: {{")
        for kind in ("pages", "more"):
            pages = found[command][kind]
            if not pages:
                continue
            out.append(f"        {kind!r}: {{")
            for i in sorted(pages):
                out.append(f"            {i}: {{")
                out += [f"                {row}: {text!r}," for row, text in sorted(pages[i].items())]
                out.append("            },")
            out.append("        },")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main(paths: list[str]) -> int:
    caps = [json.load(open(p)) for p in paths]
    found, problems = extract(caps)
    for p in problems:
        print("note:", p, file=sys.stderr)
    sys.stdout.write(render(found))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
