"""Writes docs/scenarios.md (instructor) and docs/scenarios-trainee.md (the same without the fixes) from the
scenario registry, so the lesson text lives in one place, next to the changes it describes, and cannot drift.

    python -m silverlake.scenario_docs            # rewrite both files
    python -m silverlake.scenario_docs --check    # exit 1 if either is out of date (the tests do this)"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import scenarios

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
FIELDS = ("where", "parallel", "vulnerability", "mitre", "steps", "consequence", "fix", "reference")


def missing(scn: scenarios.Scenario) -> list[str]:
    return [f for f in FIELDS if not scn.doc.get(f)] + ([] if scn.flag.get("task") else ["flag task"])


def entry(n: int, scn: scenarios.Scenario, instructor: bool) -> str:
    d = scn.doc
    lines = [f"### {n}. {scn.title}", "",
             f"**Where:** {d['where']}", "",
             f"**Real-world parallel:** {d['parallel']}", "",
             f"**Vulnerability:** {d['vulnerability']}", "",
             f"**MITRE ATT&CK:** {', '.join(d['mitre'])}", "",
             f"**Exploit:**", ""]
    lines += [f"{i}. {s}" for i, s in enumerate(d["steps"], 1)]
    lines += ["", f"**Consequence in the sim:** {d['consequence']}", "",
              f"**Flag:** {scn.flag.get('task', '')}", ""]
    if instructor:
        lines += [f"**Fix:** {d['fix']} (`./scenario.sh set {scn.id} secure`)", "",
                  f"**Reference:** {d['reference']}", ""]
    return "\n".join(lines)


def render(instructor: bool, registry: dict[str, scenarios.Scenario] | None = None) -> str:
    registry = registry or scenarios.registry()
    bad = {sid: missing(s) for sid, s in registry.items() if missing(s)}
    if bad:
        raise scenarios.ScenarioError("scenarios missing doc text: " + "; ".join(f"{k}: {', '.join(v)}" for k, v in bad.items()))
    head = ("# Silverlake scenarios" + ("" if instructor else " (trainee)") + "\n\n"
            + ("Instructor copy, with the fixes. The trainee copy is [scenarios-trainee.md](scenarios-trainee.md).\n"
               if instructor else "Each lesson says where to look, what is wrong and how to prove it. The fixes are left out.\n")
            + "\nGenerated by `python -m silverlake.scenario_docs` from `src/silverlake/data/scenarios/`. Do not edit by hand.\n"
            "Flags are checked with `./check-flags.sh`; see [flags in the README](../README.md).\n")
    out, n = [head], 0
    for group, name in scenarios.GROUPS.items():
        members = [s for s in registry.values() if s.group == group]
        if not members:
            continue
        out.append(f"## Group {group}: {name}\n")
        for s in members:
            n += 1
            out.append(entry(n, s, instructor))
    return "\n".join(out).rstrip() + "\n"


def targets() -> dict[Path, bool]:
    return {DOCS / "scenarios.md": True, DOCS / "scenarios-trainee.md": False}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m silverlake.scenario_docs")
    ap.add_argument("--check", action="store_true", help="fail if the files are out of date")
    args = ap.parse_args(argv)
    stale = []
    for path, instructor in targets().items():
        text = render(instructor)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run python -m silverlake.scenario_docs)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
