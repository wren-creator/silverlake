"""The throwaway certificate behind every TLS port.

`./setup.sh` makes one with the openssl command line tool: a self-signed 2048 bit RSA certificate for
SILVERLAKE, valid for 127.0.0.1 and localhost, kept in `.tls/` at the repo root (gitignored, like the
instance secret) or wherever SILVERLAKE_TLS_DIR says. It is regenerated by `./setup.sh --force-tls`, never by
`reset.sh`. Nothing here is a real identity: a client has to be told to trust it, which is how a self-signed
certificate on a real IBM i behaves too.

With no certificate present the TLS ports are simply not started, and the log says so."""

from __future__ import annotations

import logging
import os
import shutil
import ssl
import subprocess
import sys
from pathlib import Path

log = logging.getLogger("silverlake.tls")

ROOT = Path(__file__).resolve().parents[3]
DAYS = 825


def cert_dir() -> Path:
    return Path(os.environ.get("SILVERLAKE_TLS_DIR", ROOT / ".tls"))


def paths(directory: Path | None = None) -> tuple[Path, Path]:
    d = directory or cert_dir()
    return d / "cert.pem", d / "key.pem"


def make(directory: Path | None = None, force: bool = False) -> bool:
    """Make the certificate and key with openssl. False if openssl is missing or fails."""
    cert, key = paths(directory)
    if cert.exists() and key.exists() and not force:
        return True
    exe = shutil.which("openssl")
    if exe is None:
        return False
    cert.parent.mkdir(parents=True, exist_ok=True)
    run = subprocess.run(
        [exe, "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-sha256", "-days", str(DAYS),
         "-keyout", str(key), "-out", str(cert), "-subj", "/CN=SILVERLAKE/O=Silverlake range",
         "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1"],
        capture_output=True, text=True)
    if run.returncode != 0:
        log.warning("openssl could not make a certificate: %s", run.stderr.strip()[:200])
        return False
    key.chmod(0o600)
    return True


def minimum_version(env: dict[str, str] | None = None) -> ssl.TLSVersion:
    """TLS 1.2 unless SILVERLAKE_TLS_MIN says 1.3. Anything else is a mistake and is refused, not guessed at."""
    value = (env if env is not None else os.environ).get("SILVERLAKE_TLS_MIN", "1.2").strip()
    try:
        return {"1.2": ssl.TLSVersion.TLSv1_2, "1.3": ssl.TLSVersion.TLSv1_3}[value]
    except KeyError:
        raise ValueError(f"SILVERLAKE_TLS_MIN must be 1.2 or 1.3, not {value!r}") from None


def server_context(directory: Path | None = None) -> ssl.SSLContext | None:
    """A server side TLS context from the certificate, or None when there is not one."""
    cert, key = paths(directory)
    if not (cert.exists() and key.exists()):
        return None
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.minimum_version = minimum_version()
    ctx.load_cert_chain(cert, key)
    return ctx


def client_context(directory: Path | None = None) -> ssl.SSLContext:
    """What a test or a trainee's script uses to trust the range's certificate."""
    cert, _ = paths(directory)
    ctx = ssl.create_default_context(cafile=str(cert))
    return ctx


def main(argv: list[str] | None = None) -> int:
    force = "--force" in (argv if argv is not None else sys.argv[1:])
    if make(force=force):
        print(f"certificate in {paths()[0]}")
        return 0
    print("openssl not available or failed: TLS ports will not start", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
